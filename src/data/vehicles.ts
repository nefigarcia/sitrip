export function getModels(brand: string): string[] {
  return VEHICLE_DATA.find((b) => b.name === brand)?.models.map((m) => m.name) ?? [];
}

export function getYears(brand: string, model: string): number[] {
  const models = VEHICLE_DATA.find((b) => b.name === brand)?.models;
  const years = models?.find((m) => m.name === model)?.years ?? {};
  return Object.keys(years)
    .map(Number)
    .sort((a, b) => b - a);
}

export function getFuelEfficiency(brand: string, model: string, year: number): number | null {
  const models = VEHICLE_DATA.find((b) => b.name === brand)?.models;
  const yearData = models?.find((m) => m.name === model)?.years ?? {};
  return yearData[year] ?? null;
}
